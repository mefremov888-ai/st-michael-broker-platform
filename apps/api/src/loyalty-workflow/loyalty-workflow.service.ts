  async correctAttempt(
    assignmentId: string,
    attemptId: string,
    body: CorrectAttemptDto,
    user: CurrentUserPayload,
  ) {
    await this.permissions.require(user, "CALL_EXECUTE");
    try {
      return await this.db.$transaction(
        async (tx: any) => {
          // All authorization and chain checks deliberately live in the same
          // serializable transaction as the append. This makes the predicate
          // read below participate in PostgreSQL SSI and prevents two callers
          // from creating sibling corrections for the same current leaf.
          const original = await tx.loyaltyCallAttempt.findUnique({
            where: { id: attemptId },
            include: { assignment: { include: { campaign: true } } },
          });
          if (!original || original.assignmentId !== assignmentId)
            this.notFound();
          this.requireAssignmentExecution(
            user,
            original.assignment.assignedToId,
          );
          this.validateCallResult(
            original.assignment.campaign.entityType,
            body.result,
          );
          this.validateAttemptComment(
            original.assignment.campaign.entityType,
            body,
          );

          const existing = await tx.loyaltyCallAttempt.findUnique({
            where: { submissionId: body.submissionId },
          });
          if (existing) {
            const compatible =
              existing.assignmentId === assignmentId &&
              existing.operatorId === user.id &&
              existing.correctsAttemptId === attemptId &&
              this.sameAttemptValues(existing, body) &&
              existing.correctionReason === body.correctionReason;
            if (!compatible) this.idempotencyConflict();
            return { ...existing, idempotent: true };
          }

          const descendants = await tx.loyaltyCallAttempt.findMany({
            where: { correctsAttemptId: attemptId },
            select: { id: true },
            take: 2,
          });
          if (descendants.length) this.stateConflict();

          const correction = await tx.loyaltyCallAttempt.create({
            data: {
              assignmentId,
              submissionId: body.submissionId,
              operatorId: user.id,
              result: body.result,
              comment: this.nullable(body.comment),
              nextStep: this.nullable(body.nextStep),
              nextActionAt: body.nextActionAt
                ? new Date(body.nextActionAt)
                : null,
              correctsAttemptId: attemptId,
              correctionReason: body.correctionReason,
            },
          });
          await this.audit(
            tx,
            user.id,
            "CALL_ATTEMPT_CORRECTED",
            "CALL_ATTEMPT",
            attemptId,
            null,
            { correctionId: correction.id, result: body.result },
          );
          return { ...correction, idempotent: false };
        },
        { isolationLevel: "Serializable" as any },
      );
    } catch (error) {
      if (this.prismaCode(error) === "P2002") {
        const raced = await this.db.loyaltyCallAttempt.findUnique({
          where: { submissionId: body.submissionId },
        });
        if (
          raced &&
          raced.assignmentId === assignmentId &&
          raced.operatorId === user.id &&
          raced.correctsAttemptId === attemptId &&
          this.sameAttemptValues(raced, body) &&
          raced.correctionReason === body.correctionReason
        ) {
          return { ...raced, idempotent: true };
        }
        this.idempotencyConflict();
      }
      if (this.prismaCode(error) === "P2034") this.stateConflict();
      throw error;
    }
  }

