  private safeJson(value: unknown, maxBytes = 100_000): any {
    let serialized: string;
    try {
      serialized = this.stableStringify(value);
    } catch {
      throw new BadRequestException("Некорректный набор фильтров");
    }
    if (Buffer.byteLength(serialized, "utf8") > maxBytes) {
      throw new BadRequestException("Набор фильтров слишком большой");
    }
    return JSON.parse(serialized);
  }

  private stableStringify(value: unknown): string {
    const seen = new WeakSet<object>();
    const normalize = (item: any, depth: number): any => {
      if (depth > 20) throw new Error("depth");
      if (item === null || typeof item !== "object") return item;
      if (seen.has(item)) throw new Error("cycle");
      seen.add(item);
      if (Array.isArray(item))
        return item.map((entry) => normalize(entry, depth + 1));
      const result: Record<string, unknown> = {};
      for (const key of Object.keys(item).sort()) {
        if (["__proto__", "prototype", "constructor"].includes(key)) continue;
        if (item[key] !== undefined)
          result[key] = normalize(item[key], depth + 1);
      }
      return result;
    };
    return JSON.stringify(normalize(value, 0));
  }

  private hash(value: unknown): string {
    return createHash("sha256")
      .update(this.stableStringify(value))
      .digest("hex");
  }

