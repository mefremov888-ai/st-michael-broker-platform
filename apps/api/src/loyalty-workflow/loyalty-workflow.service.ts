  async replaceGrantProfile(
    body: ReplaceGrantProfileDto,
    user: CurrentUserPayload,
  ) {
    this.permissions.requireAdmin(user);
    const target = await this.db.broker.findFirst({
      where: {
        id: body.userId,
        role: "MANAGER",
        status: "ACTIVE",
        mergedIntoId: null,
      },
      select: { id: true },
    });
    if (!target) {
      throw new BadRequestException(
        "Профиль можно назначить только активному сотруднику",
      );
    }
    const permissions = Array.from(new Set(body.permissions)).sort();
    try {
      return await this.db.$transaction(
        async (tx: any) => {
          const active = await tx.loyaltyUserGrant.findMany({
            where: { userId: body.userId, revokedAt: null },
            select: { id: true, permission: true },
          });
          const before = active.map((item: any) => item.permission).sort();
          const expected = new Set(permissions);
          const revoked = active.filter(
            (item: any) => !expected.has(item.permission),
          );
          const now = new Date();
          if (revoked.length) {
            await tx.loyaltyUserGrant.updateMany({
              where: { id: { in: revoked.map((item: any) => item.id) } },
              data: { revokedAt: now },
            });
          }
          const current = new Set(
            active.map((item: any) => item.permission as string),
          );
          const granted: string[] = [];
          for (const permission of permissions) {
            if (current.has(permission)) continue;
            await tx.loyaltyUserGrant.create({
              data: {
                userId: body.userId,
                permission,
                grantedById: user.id,
              },
            });
            granted.push(permission);
          }
          await this.audit(
            tx,
            user.id,
            "GRANT_PROFILE_REPLACED",
            "USER_GRANT_PROFILE",
            body.userId,
            { permissions: before },
            { permissions },
          );
          return {
            userId: body.userId,
            permissions,
            granted,
            revoked: revoked.map((item: any) => item.permission),
          };
        },
        { isolationLevel: "Serializable" as any },
      );
    } catch (error) {
      if (this.prismaCode(error) === "P2034") this.stateConflict();
      throw error;
    }
  }

  async createGrant(body: CreateGrantDto, user: CurrentUserPayload) {
    this.permissions.requireAdmin(user);
    const target = await this.db.broker.findUnique({
      where: { id: body.userId },
      select: { id: true, role: true, status: true },
    });
    if (!target || target.role !== "MANAGER" || target.status !== "ACTIVE") {
      throw new BadRequestException(
        "Право можно выдать только активному сотруднику",
      );
    }
    const active = await this.db.loyaltyUserGrant.findFirst({
      where: {
        userId: body.userId,
        permission: body.permission,
        revokedAt: null,
      },
    });
    if (active) return { ...active, idempotent: true };
    try {
      return await this.db.$transaction(async (tx: any) => {
        const created = await tx.loyaltyUserGrant.create({
          data: {
            userId: body.userId,
            permission: body.permission,
            grantedById: user.id,
          },
        });
        await this.audit(
          tx,
          user.id,
          "GRANT_CREATED",
          "USER_GRANT",
          created.id,
          null,
          { userId: body.userId, permission: body.permission, active: true },
        );
        return { ...created, idempotent: false };
      });
    } catch (error) {
      if (this.prismaCode(error) === "P2002") {
        const raced = await this.db.loyaltyUserGrant.findFirst({
          where: {
            userId: body.userId,
            permission: body.permission,
            revokedAt: null,
          },
        });
        if (raced) return { ...raced, idempotent: true };
      }
      throw error;
    }
  }

  async revokeGrant(id: string, user: CurrentUserPayload) {
    this.permissions.requireAdmin(user);
    return this.db.$transaction(async (tx: any) => {
      const current = await tx.loyaltyUserGrant.findUnique({ where: { id } });
      if (!current) this.notFound();
      if (current.revokedAt) return { ...current, idempotent: true };
      const revokedAt = new Date();
      const changed = await tx.loyaltyUserGrant.updateMany({
        where: { id, revokedAt: null },
        data: { revokedAt },
      });
      if (changed.count !== 1) this.stateConflict();
      await this.audit(
        tx,
        user.id,
        "GRANT_REVOKED",
        "USER_GRANT",
        id,
        {
          userId: current.userId,
          permission: current.permission,
          active: true,
        },
        {
          userId: current.userId,
          permission: current.permission,
          active: false,
        },
      );
      return { ...current, revokedAt, idempotent: false };
    });
  }

