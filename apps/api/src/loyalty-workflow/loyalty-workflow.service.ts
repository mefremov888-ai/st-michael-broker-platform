  private async validateTargets(
    campaign: any,
    ids: string[],
    driftIsConflict = false,
    database: any = this.db,
  ): Promise<void> {
    if (!ids.length) throw new BadRequestException("Не выбраны записи");
    let found: Array<{ id: string }> = [];
    if (campaign.base === "ANNA") {
      const snapshotId =
        campaign.snapshotId ?? (await this.activeSnapshot("ANNA", database));
      const field =
        campaign.entityType === "BROKER" ? "personId" : "organizationId";
      const records = await database.loyaltySourceRecord.findMany({
        where: {
          snapshotId,
          entityType: campaign.entityType,
          sourceArchivedAt: null,
          [field]: { in: ids },
          ...(campaign.entityType === "BROKER"
            ? { person: { is: { archivedAt: null } } }
            : { organization: { is: { archivedAt: null } } }),
        },
        distinct: [field],
        select: { [field]: true },
      });
      found = records
        .map((row: any) => ({ id: row[field] }))
        .filter((row: any) => row.id);
      const foundIds = new Set(found.map((row) => row.id));
      const missingIds = ids.filter((id) => !foundIds.has(id));
      if (missingIds.length) {
        const relationName =
          campaign.entityType === "BROKER" ? "person" : "organization";
        const overlays = await database.loyaltyManualEntity.findMany({
          where: {
            entityType: campaign.entityType,
            archivedAt: null,
            dataset: { snapshots: { some: { id: snapshotId } } },
            [field]: { in: missingIds },
            [relationName]: { is: { archivedAt: null } },
          },
          select: { [field]: true },
        });
        found.push(
          ...overlays
            .map((row: any) => ({ id: row[field] }))
            .filter((row: any) => row.id),
        );
      }
    } else if (campaign.entityType === "BROKER") {
      // 2026-09-04 (задача A): «не звонить» — жёсткий стоп и на назначении:
      // брокер, помеченный doNotCall после создания кампании, делает цель
      // недоступной (нужно пересобрать выборку).
      found = await database.broker.findMany({
        where: { id: { in: ids }, mergedIntoId: null, doNotCall: false },
        select: { id: true },
      });
    } else {
      found = await database.agency.findMany({
        where: { id: { in: ids } },
        select: { id: true },
      });
    }
    if (new Set(found.map((row) => row.id)).size !== ids.length) {
      if (driftIsConflict) this.selectionDrift();
      throw new BadRequestException("Выбор содержит недоступные записи");
    }
  }

