  private async eventChainStates(
    database: any,
    seeds: any[],
  ): Promise<
    Map<string, { current: boolean; effective: boolean; superseded: boolean }>
  > {
    const select = {
      id: true,
      correctsEventId: true,
      archivedAt: true,
      createdAt: true,
    };
    const nodes = new Map<string, any>();
    for (const seed of seeds) {
      if (seed?.id) nodes.set(String(seed.id), seed);
    }
    if (!nodes.size) return new Map();

    let frontier = [...nodes.values()]
      .map((row) => row.correctsEventId && String(row.correctsEventId))
      .filter((id): id is string => Boolean(id) && !nodes.has(id));
    for (let round = 0; frontier.length && round < 100; round += 1) {
      const wanted = new Set(frontier);
      const fetchedRaw = await database.loyaltyEngagementEvent.findMany({
        where: { id: { in: [...wanted] } },
        select,
      });
      const fetched = (Array.isArray(fetchedRaw) ? fetchedRaw : []).filter(
        (row: any) => wanted.has(String(row?.id || "")),
      );
      if (!fetched.length) break;
      for (const row of fetched) nodes.set(String(row.id), row);
      if (nodes.size > 10000) this.stateConflict();
      frontier = fetched
        .map((row: any) =>
          row.correctsEventId ? String(row.correctsEventId) : null,
        )
        .filter(
          (id: string | null): id is string => Boolean(id) && !nodes.has(id!),
        );
    }
    if (frontier.length) this.stateConflict();

    const rootId = (row: any): string => {
      let current = row;
      const seen = new Set<string>();
      while (
        current?.correctsEventId &&
        nodes.has(String(current.correctsEventId)) &&
        !seen.has(String(current.correctsEventId))
      ) {
        seen.add(String(current.id));
        current = nodes.get(String(current.correctsEventId));
      }
      return String(current?.id || row.id);
    };
    const roots = new Set(
      seeds.filter((row) => row?.id).map((row) => rootId(row)),
    );
    let parentFrontier = [...roots];
    const expanded = new Set<string>();
    for (let round = 0; parentFrontier.length && round < 100; round += 1) {
      const parentIds = new Set(
        parentFrontier.filter((id) => !expanded.has(id)),
      );
      if (!parentIds.size) break;
      for (const id of parentIds) expanded.add(id);
      const childrenRaw = await database.loyaltyEngagementEvent.findMany({
        where: { correctsEventId: { in: [...parentIds] } },
        select,
      });
      const children = (Array.isArray(childrenRaw) ? childrenRaw : []).filter(
        (row: any) => parentIds.has(String(row?.correctsEventId || "")),
      );
      parentFrontier = [];
      for (const row of children) {
        const id = String(row.id);
        nodes.set(id, row);
        if (!expanded.has(id)) parentFrontier.push(id);
      }
      if (nodes.size > 10000) this.stateConflict();
    }
    if (parentFrontier.length) this.stateConflict();

    const chains = new Map<string, any[]>();
    for (const row of nodes.values()) {
      const root = rootId(row);
      if (!roots.has(root)) continue;
      const chain = chains.get(root) || [];
      chain.push(row);
      chains.set(root, chain);
    }
    const states = new Map<
      string,
      { current: boolean; effective: boolean; superseded: boolean }
    >();
    for (const chain of chains.values()) {
      const ordered = [...chain].sort((left, right) =>
        this.eventChainSortKey(left).localeCompare(
          this.eventChainSortKey(right),
        ),
      );
      const currentId = String(ordered[ordered.length - 1].id);
      const currentArchived = Boolean(ordered[ordered.length - 1].archivedAt);
      for (const row of ordered) {
        const current = String(row.id) === currentId;
        states.set(String(row.id), {
          current,
          effective: current && !currentArchived,
          superseded: !current,
        });
      }
    }
    return states;
  }

  private eventChainSortKey(row: any): string {
    const parsed = row?.createdAt ? new Date(row.createdAt) : null;
    const createdAt =
      parsed && Number.isFinite(parsed.getTime()) ? parsed.toISOString() : "";
    return `${createdAt}\u0000${String(row?.id || "")}`;
  }

