  private idempotentAttempt(
    existing: any,
    assignmentId: string,
    operatorId: string,
    body: CreateAttemptDto,
  ) {
    if (
      existing.assignmentId !== assignmentId ||
      existing.operatorId !== operatorId ||
      existing.correctsAttemptId !== null ||
      !this.sameAttemptValues(existing, body)
    ) {
      this.idempotencyConflict();
    }
    return { ...existing, idempotent: true };
  }

  private sameAttemptValues(
    existing: any,
    body: CreateAttemptDto | CorrectAttemptDto,
  ): boolean {
    const existingNext = existing.nextActionAt
      ? new Date(existing.nextActionAt).toISOString()
      : null;
    const bodyNext = body.nextActionAt
      ? new Date(body.nextActionAt).toISOString()
      : null;
    return (
      existing.result === body.result &&
      (existing.comment ?? null) === this.nullable(body.comment) &&
      (existing.nextStep ?? null) === this.nullable(body.nextStep) &&
      existingNext === bodyNext
    );
  }

  private async queueSourceRecords(rows: any[]): Promise<Map<string, any>> {
    const ors = rows
      .filter((row) => row.campaign.base === "ANNA" && row.campaign.snapshotId)
      .map((row) =>
        row.annaPersonId
          ? {
              snapshotId: row.campaign.snapshotId,
              personId: row.annaPersonId,
              person: { is: { archivedAt: null } },
            }
          : {
              snapshotId: row.campaign.snapshotId,
              organizationId: row.annaOrganizationId,
              organization: { is: { archivedAt: null } },
            },
      );
    if (!ors.length) return new Map();
    const records = await this.db.loyaltySourceRecord.findMany({
      where: { OR: ors, sourceArchivedAt: null },
      select: {
        snapshotId: true,
        personId: true,
        organizationId: true,
        displayName: true,
        city: true,
        attributes: true,
        contactPoints: {
          where: { type: "PHONE" },
          orderBy: [{ isPrimary: "desc" }, { createdAt: "asc" }],
          select: {
            value: true,
            normalizedValue: true,
            isPrimary: true,
            createdAt: true,
          },
        },
        person: {
          select: {
            contactOverrides: {
              where: { type: "PHONE", archivedAt: null },
              orderBy: [{ isPrimary: "desc" }, { createdAt: "asc" }],
              select: {
                value: true,
                normalizedValue: true,
                isPrimary: true,
                createdAt: true,
              },
            },
          },
        },
        organization: {
          select: {
            contactOverrides: {
              where: { type: "PHONE", archivedAt: null },
              orderBy: [{ isPrimary: "desc" }, { createdAt: "asc" }],
              select: {
                value: true,
                normalizedValue: true,
                isPrimary: true,
                createdAt: true,
              },
            },
          },
        },
      },
    });
    for (const record of records) {
      const overrides =
        record.person?.contactOverrides ??
        record.organization?.contactOverrides ??
        [];
      record.contactPoints = this.queuePhoneContacts(
        record.contactPoints,
        overrides,
      );
    }
    const result = new Map<string, any>(
      records.map((record: any) => [
        `${record.snapshotId}:${record.personId ?? record.organizationId}`,
        record,
      ]),
    );
    const missingRows = rows.filter((row) => {
      if (row.campaign.base !== "ANNA" || !row.campaign.snapshotId)
        return false;
      const id = row.annaPersonId ?? row.annaOrganizationId;
      return !result.has(`${row.campaign.snapshotId}:${id}`);
    });
    for (const row of missingRows) {
      const targetId = row.annaPersonId ?? row.annaOrganizationId;
      const field = row.annaPersonId ? "personId" : "organizationId";
      const relationName = row.annaPersonId ? "person" : "organization";
      const overlay = await this.db.loyaltyManualEntity.findFirst({
        where: {
          archivedAt: null,
          dataset: {
            snapshots: { some: { id: row.campaign.snapshotId } },
          },
          [field]: targetId,
          [relationName]: { is: { archivedAt: null } },
        },
        select: {
          displayName: true,
          city: true,
          contactPoints: true,
          attributes: true,
          [relationName]: {
            select: {
              contactOverrides: {
                where: { type: "PHONE", archivedAt: null },
                orderBy: [{ isPrimary: "desc" }, { createdAt: "asc" }],
                select: {
                  value: true,
                  normalizedValue: true,
                  isPrimary: true,
                  createdAt: true,
                },
              },
            },
          },
        },
      });
      if (overlay) {
        overlay.contactPoints = this.queuePhoneContacts(
          overlay.contactPoints,
          overlay[relationName]?.contactOverrides ?? [],
        );
        result.set(`${row.campaign.snapshotId}:${targetId}`, overlay);
      }
    }
    return result;
  }

  private queuePhoneContacts(source: unknown, overrides: unknown): any[] {
    const rows: Array<any & { manualOverride: boolean }> = [
      ...(Array.isArray(source)
        ? source.map((point) => ({ ...point, manualOverride: false }))
        : []),
      ...(Array.isArray(overrides)
        ? overrides.map((point) => ({ ...point, manualOverride: true }))
        : []),
    ];
    const byValue = new Map<string, (typeof rows)[number]>();
    for (const point of rows) {
      const key = String(
        point.normalizedValue || point.normalized || point.value || "",
      );
      if (!key) continue;
      const existing = byValue.get(key);
      if (!existing || point.manualOverride) byValue.set(key, point);
    }
    return [...byValue.values()].sort(
      (left, right) =>
        Number(Boolean(right.isPrimary)) - Number(Boolean(left.isPrimary)) ||
        Number(right.manualOverride) - Number(left.manualOverride) ||
        new Date(left.createdAt || 0).getTime() -
          new Date(right.createdAt || 0).getTime(),
    );
  }

