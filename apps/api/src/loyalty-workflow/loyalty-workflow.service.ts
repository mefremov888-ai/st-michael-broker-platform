  async updateTask(id: string, body: UpdateTaskDto, user: CurrentUserPayload) {
    this.permissions.requireStaff(user);
    if (
      [
        body.title,
        body.description,
        body.status,
        body.assignedToId,
        body.dueAt,
      ].every((value) => value === undefined)
    ) {
      throw new BadRequestException("Не указаны изменения задачи");
    }
    const current = await this.db.loyaltyTask.findUnique({ where: { id } });
    if (!current) this.notFound();
    if (user.role !== "ADMIN") {
      const ownTask =
        current.assignedToId === user.id &&
        (body.assignedToId === undefined || body.assignedToId === user.id);
      await this.permissions.require(
        user,
        ownTask ? "CALL_EXECUTE" : "ENTITY_EDIT",
      );
    }
    if (body.assignedToId) await this.validAssignee(body.assignedToId);
    const data: any = { version: { increment: 1 } };
    if (body.title !== undefined) data.title = body.title;
    if (body.description !== undefined)
      data.description = this.nullable(body.description ?? undefined);
    if (body.assignedToId !== undefined) data.assignedToId = body.assignedToId;
    if (body.dueAt !== undefined)
      data.dueAt = body.dueAt ? new Date(body.dueAt) : null;
    if (body.status !== undefined) {
      data.status = body.status;
      data.completedAt = body.status === "COMPLETED" ? new Date() : null;
      data.cancelledAt = body.status === "CANCELLED" ? new Date() : null;
    }
    return this.db.$transaction(async (tx: any) => {
      const changed = await tx.loyaltyTask.updateMany({
        where: { id, version: body.expectedVersion },
        data,
      });
      if (changed.count !== 1) this.versionConflict();
      const updated = await tx.loyaltyTask.findUnique({
        where: { id },
        include: {
          assignedTo: { select: { id: true, fullName: true, role: true } },
        },
      });
      await this.audit(
        tx,
        user.id,
        "TASK_UPDATED",
        "TASK",
        id,
        { status: current.status, version: current.version },
        {
          status: updated.status,
          version: updated.version,
          hasDueAt: Boolean(updated.dueAt),
        },
      );
      return this.taskResponse(updated);
    });
  }

