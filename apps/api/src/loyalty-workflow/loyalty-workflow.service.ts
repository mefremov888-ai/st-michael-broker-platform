  private async setEventArchived(
    id: string,
    expectedVersion: number,
    archived: boolean,
    user: CurrentUserPayload,
  ) {
    try {
      return await this.db.$transaction(
        async (tx: any) => {
          const current = await tx.loyaltyEngagementEvent.findUnique({
            where: { id },
            include: this.eventInclude(),
          });
          if (!current) this.notFound();
          if (current.version !== expectedVersion) this.versionConflict();
          const states = await this.eventChainStates(tx, [current]);
          if (!states.get(String(current.id))?.current) this.stateConflict();
          if (Boolean(current.archivedAt) === archived) this.stateConflict();
          const archivedAt = archived ? new Date() : null;
          const changed = await tx.loyaltyEngagementEvent.updateMany({
            where: {
              id,
              version: expectedVersion,
              archivedAt: archived ? null : { not: null },
            },
            data: { archivedAt, version: { increment: 1 } },
          });
          if (changed.count !== 1) this.versionConflict();
          const updated = await tx.loyaltyEngagementEvent.findUnique({
            where: { id },
            include: this.eventInclude(),
          });
          if (!updated) this.notFound();
          await this.audit(
            tx,
            user.id,
            archived ? "EVENT_ARCHIVED" : "EVENT_RESTORED",
            "ENGAGEMENT_EVENT",
            id,
            { archived: !archived, version: current.version },
            { archived, version: updated.version },
          );
          return this.eventResponse(updated, {
            current: true,
            effective: !archived,
            superseded: false,
          });
        },
        { isolationLevel: "Serializable" as any },
      );
    } catch (error) {
      if (this.prismaCode(error) === "P2034") this.versionConflict();
      throw error;
    }
  }

