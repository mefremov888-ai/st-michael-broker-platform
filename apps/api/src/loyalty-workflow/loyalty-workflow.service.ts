function workflowCsvCell(value: unknown): string {
  let text = value === null || value === undefined ? "" : String(value);
  if (/^\s*[=+\-@]/.test(text) || /^[\t\r]/.test(text)) text = `'${text}`;
  return `"${text.replace(/"/g, '""')}"`;
}

function workflowCsvLine(values: unknown[]): string {
  return `${values.map(workflowCsvCell).join(",")}\r\n`;
}

