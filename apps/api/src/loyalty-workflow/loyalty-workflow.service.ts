  private async selectionIds(
    campaign: any,
    body: AssignmentBatchDto,
  ): Promise<string[]> {
    if (!body.selection)
      throw new BadRequestException("Не задан выбор записей");
    const snapshot = campaign.filterSnapshot;
    const frozen = snapshot?.selection;
    if (snapshot?.version === 2) {
      const frozenIds = this.uniqueIds(snapshot.targetIds);
      if (
        !frozen ||
        typeof snapshot.selectionDigest !== "string" ||
        frozen.mode !== body.selection.mode ||
        frozenIds.length !== campaign.expectedCount ||
        this.idsDigest(frozenIds) !== snapshot.selectionDigest
      ) {
        this.selectionDrift();
      }
      if (frozen.mode === "IDS") {
        if (
          !body.selection.ids?.length ||
          body.selection.excludedIds?.length ||
          body.selection.filterHash ||
          !this.sameIds(frozenIds, this.uniqueIds(body.selection.ids))
        ) {
          this.selectionDrift();
        }
        return frozenIds;
      }
      if (
        body.selection.ids?.length ||
        !body.selection.filterHash ||
        body.selection.filterHash !== campaign.filterHash ||
        body.selection.expectedCount !== campaign.expectedCount ||
        !this.sameIds(
          this.uniqueIds(frozen.excludedIds ?? []),
          this.uniqueIds(body.selection.excludedIds ?? []),
        )
      ) {
        this.selectionDrift();
      }
      return frozenIds;
    }
    if (
      snapshot?.version !== 1 ||
      !snapshot?.query ||
      !frozen ||
      typeof snapshot.selectionDigest !== "string" ||
      frozen.mode !== body.selection.mode
    )
      this.selectionDrift();
    if (frozen.mode === "IDS") {
      if (
        !body.selection.ids?.length ||
        body.selection.excludedIds?.length ||
        body.selection.filterHash
      )
        this.selectionDrift();
      const frozenIds = this.uniqueIds(frozen.ids);
      const incomingIds = this.uniqueIds(body.selection.ids);
      if (
        !this.sameIds(frozenIds, incomingIds) ||
        frozenIds.length !== campaign.expectedCount ||
        this.idsDigest(frozenIds) !== snapshot.selectionDigest
      )
        this.selectionDrift();
      return frozenIds;
    }
    if (
      body.selection.ids?.length ||
      !body.selection.filterHash ||
      body.selection.filterHash !== campaign.filterHash ||
      body.selection.expectedCount !== campaign.expectedCount
    )
      this.selectionDrift();
    const frozenExclusions = this.uniqueIds(frozen.excludedIds ?? []);
    const incomingExclusions = this.uniqueIds(body.selection.excludedIds ?? []);
    if (!this.sameIds(frozenExclusions, incomingExclusions))
      this.selectionDrift();
    const resolved = await this.resolveCanonical(
      campaign.base,
      campaign.entityType,
      snapshot.query,
    );
    const resolvedIds = this.uniqueIds(resolved.ids);
    if (
      resolved.filterHash !== campaign.filterHash ||
      (resolved.snapshotId ?? null) !== (campaign.snapshotId ?? null) ||
      resolved.total !== snapshot.resolvedTotal ||
      resolvedIds.length !== resolved.total
    )
      this.selectionDrift();
    const excluded = new Set(frozenExclusions);
    const selectedIds = resolvedIds.filter((id) => !excluded.has(id));
    if (
      selectedIds.length !== campaign.expectedCount ||
      this.idsDigest(selectedIds) !== snapshot.selectionDigest
    )
      this.selectionDrift();
    return selectedIds;
  }

